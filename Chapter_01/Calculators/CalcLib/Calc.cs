namespace CalcLib
{
    public class Calc
    {
        public int Add(int addend1, int addend2)
        {
            return addend1 + addend2;
        }

        public int Substract(int a, int b)
        {
            return a - b;
        }

        public int Multiply(int a, int b)
        {
            return a * b;
        }

        public int Divide(int a, int b) { return a / b; }
    }
}
